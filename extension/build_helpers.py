"""Build the isolated-only helper entry; Chrome world entries must use distinct URLs."""
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parent
SOURCES=('engine-modes.js','trade-core.js','ea-options.js')
HEADER='/* Generated by build_helpers.py from our shared pure helpers. Do not edit this file directly. */\n'
def render():
    return HEADER+'\n'.join('/* '+name+' */\n'+(ROOT/name).read_text().rstrip()+'\n' for name in SOURCES)

if __name__=='__main__':
    target=ROOT/'ui-helpers.js';content=render()
    if '--check' in sys.argv:
        if not target.exists() or target.read_text()!=content:raise SystemExit('ui-helpers.js is stale; run python extension/build_helpers.py')
    else:target.write_text(content)
