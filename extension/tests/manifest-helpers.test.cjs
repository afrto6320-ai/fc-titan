const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..'),manifest=JSON.parse(fs.readFileSync(path.join(root,'manifest.json'),'utf8'));
test('MAIN and ISOLATED use disjoint script URLs and the UI helper entry precedes the interface',()=>{
 const main=new Set(manifest.content_scripts.filter(x=>x.world==='MAIN').flatMap(x=>x.js));
 const isolated=manifest.content_scripts.filter(x=>(x.world||'ISOLATED')==='ISOLATED').flatMap(x=>x.js);
 assert.deepEqual(isolated.filter(x=>main.has(x)),[]);
 assert.ok(isolated.indexOf('ui-helpers.js')>=0&&isolated.indexOf('ui-helpers.js')<isolated.indexOf('embedded.js'));
});
test('the checked-in UI entry is current and actually publishes every helper on a fresh global',()=>{
 const sources=['engine-modes.js','trade-core.js','ea-options.js'];
 const expected='/* Generated by build_helpers.py from our shared pure helpers. Do not edit this file directly. */\n'+sources.map(name=>'/* '+name+' */\n'+fs.readFileSync(path.join(root,name),'utf8').trimEnd()+'\n').join('\n');
 const code=fs.readFileSync(path.join(root,'ui-helpers.js'),'utf8');assert.equal(code,expected);
 const sandbox={window:{}};vm.createContext(sandbox);vm.runInContext(code,sandbox,{filename:'ui-helpers.js'});
 assert.equal(sandbox.window.CodexEngineModes.get('codex').label,'CODEX');assert.equal(sandbox.window.CodexTradeCore.clock(1000),'00:00:01');assert.equal(typeof sandbox.window.CodexEAOptions.groups,'function');
});
